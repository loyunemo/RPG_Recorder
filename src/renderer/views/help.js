export function openHelpDialog() {
  const root = document.getElementById('modal-root');
  const close = () => render(root);

  const mask = h('div.modal-mask', { onclick: (e) => { if (e.target === mask) close(); } },
    h('div.modal', { style: { width: 'min(680px, 94vw)' } },
      h('h2', {}, '骰式语法速查'),
      h('p.sub', {}, '所有掷骰都带随机种子，可在日志中一键复现校验。'),

      h('table.help-table', {}, SYNTAX.map(([code, desc]) =>
        h('tr', {}, h('td', {}, code), h('td', {}, desc)))),

      h('h2', { style: { marginTop: '22px' } }, '各系统判定规则'),
      ...NOTES.flatMap(([title, lines]) => [
        h('h3', { style: { margin: '14px 0 6px', fontSize: '13.5px', color: 'var(--text)' } }, title),
        h('ul', { style: { margin: 0, paddingLeft: '19px', fontSize: '12.5px', color: 'var(--text-dim)', lineHeight: '1.8' } },
          lines.map(l => h('li', {}, l))),
      ]),

      h('div.tiny.muted', { style: { marginTop: '18px', fontSize: '11px' } },
        '匕首心的护甲与职业数据取自 Daggerheart System Reference Document 1.0，© Critical Role, LLC.，',
        '依 Darrington Press Community Gaming License 使用。'),

      h('div.modal-foot', {}, h('button.btn.primary', { onclick: close }, '知道了')),
    ));

  render(root, mask);
}
